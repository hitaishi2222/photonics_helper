"""Reproduction: spatiotemporal modulation instability (STMI) sidebands in a
GRIN multimode fibre (Wright et al. 2015).

Reference
---------
L. G. Wright, Z. Liu, D. A. Nolan, M.-J. Li, D. N. Christodoulides &
F. W. Wise, "Self-organized instability in graded-index multimode fibres",
Nat. Photonics 10, 471-476 (2016), doi:10.1038/nphoton.2015.60
(arXiv:1603.07414).

What is reproduced
------------------
The paper's central nonlinear effect after beam-cleanup is spatiotemporal
modulation instability (STMI): once the field has self-organized to the
attractor (fundamental mode of the 13-um GRIN fibre, ~1.5 uJ / ~1 ns pulses
at 532 nm), cascades of FWM sidebands appear whose frequencies are fixed by
GRIN-modulated phase matching (paper Figs. 1, 3).  Fig. 3d shows the averaged
sideband shifts vs "MI order"; the theory family there is the modal-ladder
spatiotemporal phase matching of the GRIN fibre.

Checks
------
1. ANALYTIC (paper Fig. 3d): with the paraxial GRIN ladder
   beta_N(w) ~ beta0(w) - N*kappa (kappa = sqrt(2*Delta)/a), the
   signal/idler pair of ladder order N at +-Omega phase-matches through the
   symmetric material-dispersion sum

       Delta(Omega) = beta0(w0+O) + beta0(w0-O) - 2 beta0(w0)
                      - 2 N kappa + 2 gamma_f P0 = 0,

   evaluated with real fused-silica Sellmeier dispersion.  The roots track
   the digitized Fig. 3d circles to <=~11 % for orders N = 2..5 (the paper's
   hyperbolic |Omega| ~ sqrt(N) branch).
2. ENGINE: a 3-channel multimode run — CW pump in the fundamental + a
   white-noise-seeded degenerate sideband pair carrying the GRIN modal phase
   through ``phase_offsets`` = -N*kappa (the same mechanism validated by the
   Krupa GPI reproduction) — develops stable spectral peaks at the analytic
   Omega_N to within 3 % (grid resolution 0.05 THz).
3. ENERGY: total photon bookkeeping conserved over the FWM runs to < 2 %.

Model caveats (documented, not hidden)
--------------------------------------
- The engine's retarded-frame Taylor starts at beta2; the ladder phase is
  injected via ``phase_offsets`` (the discrete-modal-grating mechanism).
- Only symmetric (signal+idler) observables are asserted, so the open
  ISSUES.md #0 dispersion time-direction convention (odd-order terms) is not
  exercised by these checks.
- The order-(-1) circle of Fig. 3d (+2 THz) is generated by the Stokes
  sidebands acting as pumps (theory family Stokes-1/2 in the same panel); it
  is NOT on the chromatic ladder and is recorded, not asserted.
- The full self-organized instability cascade (55 modes, disorder/Raman
  mode-coupling network, Fig. 4 attractor-gain comparison across 11 spatial
  seeds) is out of scope: this reproduction validates the STMI phase-matching
  backbone on the experiment's own fibre parameters.

Usage
-----
    python reproductions/planned/wright_2015_self_organized_instability/reproduce.py
"""

