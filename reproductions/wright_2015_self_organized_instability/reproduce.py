PAPER_STOKES_ORDER1_THZ = 2.0

# --- Sellmeier, fused silica (Malitson) ------------------------------------
SL_B = (0.6961663, 0.4079426, 0.8974794)
SL_C = (0.0684043**2, 0.1162414**2, 9.896161**2)

PUMP_THZ = C_THZ / 0.532


# ---------------------------------------------------------------------------
# material dispersion (real Sellmeier)
# ---------------------------------------------------------------------------


def n_silica(f_thz: float) -> float:
    """Fused-silica refractive index at frequency f (THz)."""
    wl_um = C_THZ / f_thz
    l2 = wl_um**2
    return float(
        np.sqrt(1.0 + sum(b * l2 / (l2 - c) for b, c in zip(SL_B, SL_C)))
    )


def beta0(f_thz: float) -> float:
    """Material propagation constant beta0(omega) in rad/m at f (THz)."""
    wl_um = C_THZ / f_thz
    return float(2.0 * np.pi * n_silica(f_thz) / (wl_um * 1e-6))


def beta1_silica(lambda_um: float) -> float:
    """beta1(omega) = d beta0/d omega (s/m), central differences in lambda."""
    h = 1e-4  # um
    om_hi = 2.0 * np.pi * C_MS / ((lambda_um - h) * 1e-6)
    om_lo = 2.0 * np.pi * C_MS / ((lambda_um + h) * 1e-6)
    b_hi = beta0(C_THZ / (lambda_um - h))
    b_lo = beta0(C_THZ / (lambda_um + h))
    return float((b_hi - b_lo) / (om_hi - om_lo))


def beta2_silica(lambda_nm: float) -> float:
    """beta2 (s^2/m) numerically from Sellmeier at lambda (nm)."""
    lam_um = lambda_nm / 1000.0
    h = 2e-3  # um
    dom = 2.0 * np.pi * C_MS * (
        1.0 / ((lam_um - h) * 1e-6) - 1.0 / ((lam_um + h) * 1e-6)
    )  # rad/s, NEGATIVE for lambda increasing (red)
    db1_dlam = (
        beta1_silica(lam_um + h) - beta1_silica(lam_um - h)
    ) / (2.0 * h)  # s/m per um (beta1 decreases toward blue)
    # dom = omega(lam-h) - omega(lam+h) over 2h  ->  d omega/d lambda = -dom/(2h)
    return float(-(2.0 * h) * db1_dlam / dom)  # d beta1 / d omega


# ---------------------------------------------------------------------------
# analytic STMI phase matching (the backbone of paper Fig. 3d)
# ---------------------------------------------------------------------------


def gamma_eff() -> float:
    """(2/3) gamma — lp_degenerate XPM/FWM weight of the degenerate pair."""
    return (2.0 / 3.0) * 2.0 * np.pi * N2 / LAMBDA0 / A_EFF


def delta_kappa(om_thz: float, n_ord: int) -> float:
    """Total pair mismatch per channel at detuning Omega (THz), rad/m.

    Delta = 0.5*(symmetric material sum) - N kappa + gamma_f P0
    (the phase-matching condition is the pairwise sum + 2 gamma_f P0).
    """
    sym = (
        beta0(PUMP_THZ + om_thz) + beta0(PUMP_THZ - om_thz)
        - 2.0 * beta0(PUMP_THZ)
    )
    return 0.5 * sym - n_ord * KAPPA + gamma_eff() * P0_W


def stmi_shift_thz_corrected(n_ord: int, om_lo=0.5, om_hi=270.0) -> float:
    """Corrected-machine analytic root (ISSUES.md #10 resolution).

    Engine-effective pair mismatch ``dbar = 0.5*sym - N*kappa - gamma*P0/3``
    (the pump self-phases at full gamma P0 while the sideband diagonals
    carry only (2/3) gamma P0; see ``probe_gain``). The legacy
    ``stmi_shift_thz`` used the +gamma_eff P0 bookkeeping and misses the
    root by +0.015-0.022 THz.
    """
    gamma_full = 2.0 * np.pi * N2 / LAMBDA0 / A_EFF
    tmp = gamma_full * P0_W / 3.0

    def f(om: float) -> float:
        sym = (
            beta0(PUMP_THZ + om) + beta0(PUMP_THZ - om) - 2.0 * beta0(PUMP_THZ)
        )
        return 0.5 * sym - n_ord * KAPPA - tmp

    xs = np.linspace(om_lo, om_hi, 60000)
    vals = np.array([f(x) for x in xs])
    idx = np.where(np.diff(np.sign(vals)) != 0)[0]
    if len(idx) == 0:
        raise RuntimeError(f"no corrected root for order {n_ord}")
    return float(brentq(f, xs[idx[0]], xs[idx[0] + 1]))


def check_b_deterministic(n_ord: int, L: float = 0.1, n_grid: int = 32768):
    """Deterministic check B' (ISSUES.md #10 tasks 6.1-6.3).

    Coherent conjugate-tone probe at the CORRECTED analytic root
    ``stmi_shift_thz_corrected``; asserts the measured exponent against the
    exact reduced 2x2 model:

        |b2|/a = sinh(g L), g = sqrt(c^2 - dbar^2),
        c = (2/3) gamma P0, dbar = 0.5 sym - N kappa - gamma P0/3,

    with an off-resonance control ~ 0 (no peak picking over a noise floor).
    Returns the metrics dict; raises AssertionError on failure.
    """
    global N_GRID
    old_n = N_GRID
    N_GRID = n_grid
    try:
        f_root = stmi_shift_thz_corrected(n_ord)
        f_off = f_root + 20.0
        res = probe_gain(n_ord, f_thz=f_root, L=L)
        res_off = probe_gain(n_ord, f_thz=f_off, L=L)
        c = (2.0 / 3.0) * (2.0 * np.pi * N2 / LAMBDA0 / A_EFF) * P0_W
        g = c  # dbar = 0 exactly at the corrected root
        b2_analytic = float(np.sinh(g * L))
        b2_meas = float(res["cols_a1"][1])
        err = abs(b2_meas - b2_analytic) / b2_analytic
        b2_off = float(res_off["cols_a1"][1])
        assert err < 0.20, (
            f"check B' growth mismatch: measured |b2|/a = {b2_meas:.4f}, "
            f"analytic sinh(gL) = {b2_analytic:.4f} ({err*100:.1f} %)"
        )
        assert b2_off < 0.05 * b2_meas, (
            f"off-resonance control not suppressed: |b2|/a = {b2_off:.4f}"
        )
        return {
            "n_ord": n_ord,
            "L_m": L,
            "root_corrected_thz": round(f_root, 4),
            "root_legacy_thz": round(stmi_shift_thz(n_ord), 4),
            "b2_analytic": round(b2_analytic, 4),
            "b2_measured": round(b2_meas, 4),
            "rel_err_pct": round(100.0 * err, 2),
            "b2_offresonance": round(b2_off, 4),
            "energy_drift_pct": float(res["energy_drift_pct"]),
        }
    finally:
        N_GRID = old_n

def stmi_shift_thz(n_ord: int) -> float:
    """Positive phase-matched detuning |Omega| (THz) for ladder order N."""

    def f(om: float) -> float:
        return delta_kappa(om, n_ord)

    xs = np.linspace(1.0, 270.0, 6000)
    vals = np.array([f(x) for x in xs])
    idx = np.where(np.diff(np.sign(vals)) != 0)[0]
    if len(idx) == 0:
        raise RuntimeError(f"no phase-matched root for order {n_ord}")
    return float(brentq(f, xs[idx[0]], xs[idx[0] + 1]))


def mi_gain_analytic(om_thz_grid: NDArray, n_ord: int) -> NDArray:
    """g(Omega) = sqrt((gamma_f P0)^2 - Delta(Omega)^2), 1/m."""
    gf = gamma_eff() * P0_W
    dk = np.array([delta_kappa(float(o), n_ord) for o in om_thz_grid])
    return np.sqrt(np.clip(gf**2 - dk**2, 0.0, None))


