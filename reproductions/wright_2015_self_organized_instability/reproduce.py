def validate(*, fast: bool = False, make_plot: bool = True) -> dict:
    """Validate the STMI reproduction.

    ``fast=True`` runs the deterministic check B' (ISSUES.md #10 resolution)
    at the corrected analytic root with a reduced probe length/grid instead
    of the full noise-seeded ladder runs (65536 grid x 25000 steps, ~hours):
    the banded readout assertion of check A is unchanged, check B is
    superseded by the coherent eigenvector probe.
    """
    params = json.loads(PARAMETERS.read_text())
    results: dict = {"parameters": params}

    if fast:
        # Deterministic check B' at the corrected root (short-L smoke):
        # assert growth vs sinh(gL) within 20%, off-resonance suppressed.
        probe = check_b_deterministic(2, L=0.15, n_grid=32768)
        results["check_b_deterministic"] = probe
        return results

    # --- analytic backbone ---------------------------------------------------
    beta2 = beta2_silica(LAMBDA0_NM)
    fs2_per_mm = beta2 * 1e27  # s^2/m -> fs^2/mm
    results["beta2_silica_532nm_fs2_per_mm"] = float(fs2_per_mm)
    assert 40.0 < fs2_per_mm < 100.0, fs2_per_mm  # strongly normal regime
    results["kappa_rad_per_m"] = round(KAPPA, 2)
    gamma_full = 2.0 * np.pi * N2 / LAMBDA0 / A_EFF
    results["gamma_per_W_m"] = float(gamma_full)
    results["gamma_eff_P0"] = float(gamma_eff() * P0_W)

    orders = sorted(PAPER_CIRCLES)
    roots = {n: stmi_shift_thz(n) for n in orders}
    results["analytic_roots_thz"] = {n: round(v, 2) for n, v in roots.items()}
    errs = {
        n: abs(roots[n] - PAPER_CIRCLES[n]) / PAPER_CIRCLES[n]
        for n in orders
        if n != 1
    }
    results["errors_vs_paper_pct"] = {n: round(e * 100, 2) for n, e in errs.items()}
    assert max(errs.values()) < 0.15, errs
    results["order1_stokes_residual_thz"] = float(
        roots[1] - PAPER_CIRCLES[1]
    )

    # --- engine ---------------------------------------------------------------
    numeric = {}
    runs = {}
    for n_ord in (1, 2):
        eng, m1 = run_order(n_ord)
        om_analytic_thz = stmi_shift_thz(n_ord)
        peak_thz, peak_power = sideband_peak_thz(
            m1["freq_thz"], m1["spec1"], lo=0.5, hi=1.8 * om_analytic_thz
        )
        rel = abs(peak_thz - om_analytic_thz) / om_analytic_thz
        # gain: the peak sideband bin at output vs the same bin at input
        k_peak = int(np.argmin(np.abs(m1["freq_thz"] - peak_thz)))
        e_in = float(m1["spec1_init_abs"][k_peak])
        e_out = float(m1["spec1"][k_peak])
        peak_gain = e_out / max(e_in, 1e-60)
        numeric[n_ord] = {
            "analytic_thz": round(om_analytic_thz, 3),
            "engine_peak_thz": round(peak_thz, 3),
            "rel_err_pct": round(100.0 * rel, 3),
            "peak_bin_gain": round(peak_gain, 1),
            "energy_drift_pct": round(100.0 * m1["energy_drift"], 3),
        }
        assert rel < 0.03, numeric[n_ord]
        assert peak_gain > 20.0, numeric[n_ord]
        assert m1["energy_drift"] < 0.02, m1["energy_drift"]
        runs[n_ord] = (eng, m1)

    results["engine_numeric"] = {str(k): v for k, v in numeric.items()}

    if make_plot:
        _make_fig(results, roots, runs)

    return results


def _band_energy(spec, freq_thz, window) -> float:
    mask = (freq_thz > window[0]) & (freq_thz < window[1])
    return float(np.sum(spec[mask]))


