def betas_taylor(orders: int = 4) -> list[float]:
    """Even-order pair-sum dispersion of fused silica at 532 nm (SI list).

    The pair resonance depends on the symmetric sum ``sym(Omega) = beta0(w0+O)
    + beta0(w0-O) - 2 beta0(w0)``, in which every odd dispersion order cancels
    exactly; the engine therefore only needs the even orders (odd coefficients
    passed as 0.0).  The even coefficients are extracted by least squares on
    ``sym_real(Omega)`` against the scaled basis ``(Omega/Omega_max)^(2m)``
    (plain lstsq on unscaled powers is numerically hopeless here), over
    60-200 THz, then inverted from
    ``sym(O) = sum_m 2*beta_{2m}/(2m)! * O^(2m)`` (Omega in rad/ps).

    Returns a flat engine-ready list ``[beta2, 0, beta4, 0, beta6, 0,
    beta8, 0]`` (SI, s^k/m).  The engine must be fed this: a beta2-only
    engine misses the beta4+ pieces of the pair sum, which at these
    detunings contribute O(30) rad/m - larger than the whole gain band
    (+-6.27 rad/m).  Root cause of the failed check B of the earlier
    session.
    """
    f_grid = np.linspace(60.0, 200.0, 14)          # THz; covers all assert roots
    om = 2.0 * np.pi * f_grid                      # rad/ps
    sym_vals = np.array([
        beta0(PUMP_THZ + f) + beta0(PUMP_THZ - f) - 2.0 * beta0(PUMP_THZ)
        for f in f_grid
    ])
    om_max = float(om[-1])
    om_n = om / om_max
    cols = np.power.outer(om_n, 2.0 * np.arange(1, orders + 1))
    coefs, *_ = np.linalg.lstsq(cols, sym_vals, rcond=None)
    out: list[float] = []
    for m, a_m in enumerate(coefs, start=1):
        k = 2 * m
        beta_ps = a_m / om_max**k * factorial(k) / 2.0   # ps^k/m
        out.append(float(beta_ps / 1e12**k))             # s^k/m
        out.append(0.0)                                  # odd order (cancels)
    return out


def build_engine(
    *, n_ord: int, length_m: float, step_m: float, noise_rms: float = 1e-6
) -> MultimodeSplitStepEngine:
    """Pump (ch0, CW) + noise-seeded degenerate sideband pair (ch1, ch2).

    phase_offsets = [0, -N kappa, -N kappa] injects the GRIN modal-ladder
    phase of the sideband mode group N; betas shared (silica beta2 at
    532 nm); coef_model lp_degenerate (SPM 1, XPM 2/3, FWM 2/3).
    """
    grid = TemporalGrid(N=N_GRID, Tmax=Time(WINDOW_PS * 1e-12, "s"))
    a_pump = float(np.sqrt(P0_W))
    rng = np.random.default_rng(90210 + n_ord)
    waves: list[Wave] = []
    for ch in range(N_MODES):
        wave = Wave(
            grid=grid,
            envelope=Envelope(
                shape="gaussian",
                peak_amplitude=a_pump if ch == 0 else noise_rms * a_pump,
                pulse_width=Time(WINDOW_PS * 1e-12 / 4.0, "s"),
            ),
            central_wavelength=Wavelength(LAMBDA0_NM, "nm"),
        )
        if ch == 0:
            field = np.full(N_GRID, a_pump, dtype=complex)
        else:
            sig = noise_rms * a_pump / np.sqrt(2.0)
            field = rng.normal(0.0, sig, N_GRID) + 1j * rng.normal(
                0.0, sig, N_GRID
            )
        wave = wave.with_field(field)
        waves.append(wave)

    fiber = FiberProfile(
        n2=N2, alpha=0.0, A_eff=Area(A_EFF, "m^2"), length=Length(length_m, "m")
    )
    return MultimodeSplitStepEngine(
        waves,
        fiber,
        betas=[BETAS_FLAT] * N_MODES,
        betas_unit="s^k/m",
        phase_offsets=[0.0, float(-n_ord * KAPPA), float(-n_ord * KAPPA)],
        oam_l=[0, 0, 0],
        coef_model="lp_degenerate",
        include_fwm=True,
        fwm_pump_depletion=True,
        step_size=Length(step_m, "m"),
    )


BETAS_FLAT = betas_taylor()
PROBE_RMS = 1e-5  # coherent probe tone amplitude / pump amplitude


def probe_gain(n_ord: int, f_thz: float | None = None, L: float = 0.5) -> dict:
    """Deterministic engine-side parametric-gain probe (check B').

    Propagates a CW pump plus a coherent conjugate tone pair (a1 at +Om in
    ch1, a2 at -Om in ch2, each gPROBE_RMS * pump amplitude) through the
    engine and reads back the time-domain projection amplitudes of the two
    sideband channels.  Reference: the exact reduced 2x2 model

        |b1(L)|/|b1(0)| = cosh(g L),   |b2(L)|/|b1(0)| = sinh(g L),

    with g = sqrt(c^2 - dbar^2) and
        dbar = 0.5*sym(Omega) - N*kappa - (gamma P0)/3,
    c = (2/3) gamma P0 (FWM creation coupling), gamma the full Kerr
    coefficient; dbar is the engine's effective pair mismatch (the corrected
    Kerr term of ISSUES.md #10 - the pump self-phases at full gamma P0 while
    the sideband XPM diagonals carry only (2/3) gamma P0).
    """
    if f_thz is None:
        f_thz = stmi_shift_thz(n_ord)
    om = 2.0 * np.pi * f_thz * 1e12
    half_steps = int(round(L / STEP_M_LADDER))
    dz = L / half_steps
    grid = TemporalGrid(N=N_GRID, Tmax=Time(WINDOW_PS * 1e-12, "s"))
    tt = grid.t.as_s if hasattr(grid.t, "as_s") else grid.t
    tone = np.exp(1j * om * tt)
    a_sig = PROBE_RMS * float(np.sqrt(P0_W))

    def one_run(seed: tuple[float, float]) -> tuple[float, float]:
        """Seed (a1 tone weight, a2 tone weight); return output amplitudes."""
        waves: list[Wave] = []
        for ch in range(N_MODES):
            ww = Wave(
                grid=grid,
                envelope=Envelope(
                    shape="gaussian",
                    peak_amplitude=float(np.sqrt(P0_W)),
                    pulse_width=Time(WINDOW_PS * 1e-12 / 4.0, "s"),
                ),
                central_wavelength=Wavelength(LAMBDA0_NM, "nm"),
            )
            if ch == 0:
                field = np.full(N_GRID, float(np.sqrt(P0_W)), dtype=complex)
            elif ch == 1:
                field = a_sig * seed[0] * tone
            else:
                field = a_sig * seed[1] * np.conj(tone)
            waves.append(ww.with_field(np.asarray(field, complex)))
        fiber = FiberProfile(
            n2=N2, alpha=0.0, A_eff=Area(A_EFF, "m^2"), length=Length(L, "m")
        )
        eng = MultimodeSplitStepEngine(
            waves,
            fiber,
            betas=[BETAS_FLAT] * N_MODES,
            betas_unit="s^k/m",
            phase_offsets=[0.0, float(-n_ord * KAPPA), float(-n_ord * KAPPA)],
            oam_l=[0, 0, 0],
            coef_model="lp_degenerate",
            include_fwm=True,
            fwm_pump_depletion=True,
            step_size=Length(dz, "m"),
        )
        eng.propagate(half_steps, nsaves=2)
        a1_abs, a2_abs = A_proj(eng, grid, tone)
        drift = float(100.0 * abs(
            eng.energy_vs_z[-1] / eng.energy_vs_z[0] - 1.0))
        return a1_abs / a_sig, a2_abs / a_sig, drift

    def A_proj(eng, grid, tone):
        a1 = float(np.abs(np.asarray(eng.A[1], complex) @ np.conj(tone)) / N_GRID)
        a2 = float(
            np.abs(np.asarray(eng.A[2], complex) @ np.conj(np.conj(tone))) / N_GRID
        )
        return a1, a2

    proj1 = one_run((1.0, 0.0))   # seed a1 tone only
    proj2 = one_run((0.0, 1.0))   # seed a2 tone only
    _drift_pct = max(proj1[2], proj2[2])
    proj1, proj2 = proj1[:2], proj2[:2]
    return {
        "f_thz": float(f_thz),
        "L_m": L,
        "cols_a1": proj1,          # (|b1 out|/a_sig, |b2 out|/a_sig)
        "cols_a2": proj2,
        "energy_drift_pct": float(_drift_pct),
    }


def run_order(n_ord: int) -> tuple[MultimodeSplitStepEngine, dict]:
    """Propagate and return (engine, metrics)."""
    if n_ord == 0:
        step_m, num_steps = STEP_M_BASE, NUM_STEPS_BASE
    else:
        step_m, num_steps = STEP_M_LADDER, NUM_STEPS_LADDER
    eng = build_engine(
        n_ord=n_ord, length_m=step_m * num_steps, step_m=step_m
    )
    spec0 = np.abs(eng.grid.fft(np.asarray(eng.A[1], dtype=complex))) ** 2
    eng.propagate(num_steps, nsaves=min(num_steps, 33))
    freq_thz = np.abs(eng.grid.w) / (2.0 * np.pi * 1e12)
    spec1 = np.abs(eng.grid.fft(np.asarray(eng.A[1], dtype=complex))) ** 2
    spec2 = np.abs(eng.grid.fft(np.asarray(eng.A[2], dtype=complex))) ** 2
    energy = eng.energy_vs_z
    drift = float(abs(energy[-1] / energy[0] - 1.0))
    return eng, {
        "freq_thz": freq_thz,
        "spec1": spec1 * 0.0 + spec1,  # keep intensity only
        "spec2": spec2 * 0.0 + spec2,
        "spec1_init_abs": spec0.copy(),
        "energy_drift": drift,
    }


def sideband_peak_thz(
    freq_thz: NDArray, spec: NDArray, lo: float = 0.5, hi: float | None = None
) -> tuple[float, float]:
    """Spectral peak of one sideband half-plane within (lo, hi) THz."""
    if hi is None:
        hi = 260.0
    mask = (freq_thz > lo) & (freq_thz < hi)
    if mask.sum() < 8:
        raise RuntimeError("sideband search window too narrow")
    i = int(np.argmax(spec[mask]))
    return float(freq_thz[mask][i]), float(spec[mask][i])


