def _sech(x):
    return 1.0 / np.cosh(x)


def _make_pulse(grid: TemporalGrid, params: dict, peak_W: float,
                T0_ps: float) -> Wave:
    """Custom sech envelope with the given field peak (2 W -> N = 2, 1 W -> N = 1)."""
    env = Envelope(
        shape="custom",
        peak_amplitude=peak_W,
        pulse_width=Time(T0_ps * 1e-12, "s"),
        func=lambda t, T0, A0: A0 * _sech(t / T0),
    )
    lam = params["engine_mapping"]["central_wavelength_nm"]
    return Wave(
        grid=grid,
        envelope=env,
        central_wavelength=Wavelength(lam, "nm"),
    )


def _run_engine(params: dict, *, fundamental: bool = False,
                num_steps: int | None = None) -> tuple[TemporalGrid, np.ndarray, np.ndarray]:
    """Propagate with the engine; return (grid, z_array, H[nz, nx] complex).

    ``fundamental=True`` runs the N = 1 soliton (peak 1 W) to z = pi/4 for
    check 1a; otherwise the paper's N = 2 problem over [0, pi/2].
    """
    g = params["grid"]
    em = params["engine_mapping"]
    grid = TemporalGrid(N=g["N"], Tmax=Time(g["Tmax_ps"] * 1e-12, "s"))
    if fundamental:
        peak, z_span = 1.0, math.pi / 4.0
    else:
        peak, z_span = em["peak_power_W"], em["z_span_m"]
    pulse = _make_pulse(grid, params, peak, em["T0_ps"])
    fiber = FiberProfile.from_gamma(
        gamma=em["gamma_per_W_m"],
        n2=2.6e-20,
        omega0=2 * np.pi * C_MS / (em["central_wavelength_nm"] * 1e-9),
        length=Length(z_span, "m"),
    )
    solver = GNLSESolver(
        pulse=pulse,
        fiber=fiber,
        betas=np.array([em["beta2_ps2_per_m"]]),
        include_raman=False,
        include_self_steepening=False,
        include_tpa=False,
    )
    steps = num_steps or g["num_steps"]
    solver.propagate(steps, nsaves=2 if fundamental else g["n_snapshots"])
    H = np.array([w.envelope_field for w in solver.evolution])
    return grid, np.asarray(solver.z_array), H


def analytic_fundamental(t_s: np.ndarray, z: float, T0_s: float) -> np.ndarray:
    """N = 1 soliton of A_z = i(|beta2|/2) A_TT + i gamma |A|^2 A with
    |beta2| = gamma = T0 = 1 (engine units): A = sech(T/T0) e^{i z/2}."""
    return _sech(t_s / T0_s) * np.exp(1j * z / 2.0)


def _rk4ip_reference(grid: TemporalGrid, A0: np.ndarray, z_span: float,
                     n_steps: int, *, T_s: float = 1e-12,
                     L_s: float = 1.0) -> np.ndarray:
    """Independent RK4IP split-step integrator (Hult 2007) for
    A_z = i(0.5 A_TT + |A|^2 A) on the engine's grid; cross-check 1b."""
    # linear multiplier of A_z = -i(beta2/2) A_TT + i gamma |A|^2 A:
    # A_TT -> -w^2 under the FFT pair, so D(w) = +i beta2 w^2 / 2
    # (beta2 < 0 makes D negative-imaginary in w: focusing).
    w = 2 * np.pi * np.fft.fftfreq(len(A0), d=grid.dt)
    beta2_si = -(T_s**2) / L_s  # s^2/m (negative, focusing)
    D = 0.5j * beta2_si * w**2

    def N(a):
        return 1j * np.abs(a) ** 2 * a

    def L(a, h):
        return np.fft.ifft(np.exp(D * h) * np.fft.fft(a))

    dz = z_span / n_steps
    A = A0.copy()
    for _ in tqdm(range(n_steps), desc="rk4ip-cross-check", leave=False,
                  unit="step"):
        Ah = L(A, dz / 2)
        k1 = N(Ah)
        k2 = N(L(Ah + dz / 2 * k1, dz / 2))
        k3 = N(L(Ah + dz / 2 * k2, dz / 2))
        k4 = N(L(Ah + dz * k3, dz))
        A = L(Ah + dz / 6 * (k1 + 2 * k2 + 2 * k3 + k4), dz / 2)
    return A


def rel_l2(err: np.ndarray, ref: np.ndarray) -> float:
    return float(np.linalg.norm(err) / np.linalg.norm(ref))


def validate_data(params: dict) -> dict:
    """Checks 1a-1d: the engine data is trustworthy before PINN training."""
    g = params["grid"]
    tol = params["validation_tolerances"]
    out: dict = {}

    # 1a — fundamental-soliton sector vs the closed form
    grid, z_arr, H1 = _run_engine(params, fundamental=True, num_steps=40000)
    A_exact = analytic_fundamental(grid.t, float(z_arr[-1]), 1e-12)
    out["fundamental_z_over_pi"] = float(z_arr[-1] / math.pi)
    out["fundamental_max_abs_err"] = float(np.max(np.abs(H1[-1] - A_exact)))
    out["fundamental_rel_l2"] = rel_l2(H1[-1] - A_exact, A_exact)

    # 1b/1c/1d — the paper's N = 2 problem
    grid, z_arr, H = _run_engine(params)
    t_s = grid.t
    x = t_s / 1e-12

    # 1b: independent RK4IP at 4x steps, same grid
    em = params["engine_mapping"]
    A_ref = _rk4ip_reference(
        grid, H[0], float(em["z_span_m"]), 4 * g["num_steps"],
        T_s=em["T_s_ps"] * 1e-12, L_s=em["L_s_m"])
    out["cross_check_rel_l2_final"] = rel_l2(H[-1] - A_ref, A_ref)
    z_mid = float(z_arr[len(z_arr) // 2])
    A_ref_mid = _rk4ip_reference(
        grid, H[0], z_mid, max(1, 2 * g["num_steps"]),
        T_s=em["T_s_ps"] * 1e-12, L_s=em["L_s_m"])
    out["cross_check_rel_l2_mid"] = rel_l2(H[len(z_arr) // 2] - A_ref_mid,
                                           A_ref_mid)

    # 1c: breather recurrence at z = pi/2
    out["recurrence_rel_l2"] = rel_l2(np.abs(H[-1]) - 2.0 * _sech(x),
                                      2.0 * _sech(x))

    # 1d: energy (photon-number analog) conservation
    energies = np.array([np.sum(np.abs(h) ** 2) for h in H])
    out["energy_drift"] = float(np.max(np.abs(energies / energies[0] - 1.0)))

    assert out["fundamental_max_abs_err"] < tol["fundamental_soliton_max_abs_err"], out
    assert out["cross_check_rel_l2_final"] < tol["cross_check_rel_l2"], out
    assert out["cross_check_rel_l2_mid"] < tol["cross_check_rel_l2_mid"], out
    assert out["recurrence_rel_l2"] < tol["recurrence_rel_l2"], out
    assert out["energy_drift"] < tol["data_energy_drift"], out
    return out


