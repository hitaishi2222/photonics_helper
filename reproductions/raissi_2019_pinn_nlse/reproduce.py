#!/usr/bin/env python3
"""Reproduce the Schrodinger-example PINN of Raissi, Perdikaris & Karniadakis,
"Physics-informed neural networks: A deep learning framework for solving
forward and inverse problems involving nonlinear PDEs", J. Comput. Phys. 378,
686 (2019), doi:10.1016/j.jcp.2018.10.045 — with the ground-truth data
generated by photonics_helper instead of Chebfun.

The article (Sec. 2.2)
----------------------
The continuous-time PINN is applied to the periodic focusing NLSE

    i h_t + 0.5 h_xx + |h|^2 h = 0,   x in [-5, 5],  t in [0, pi/2],
    h(0, x) = 2 sech(x),              h(t, -5) = h(t, 5),  h_x(t, -5) = h_x(t, 5).

h(0, x) = 2 sech(x) is the N = 2 soliton (N^2 = gamma P0 T0^2 / |beta2| = 4 in
the units below), so the window t in [0, pi/2] is exactly one breather
period.  The paper generates the reference with Chebfun (256 Fourier modes,
RK4, dt = pi/2 * 1e-6), keeps N0 = 50 points of h(0, x) on the initial line,
Nb = 50 random boundary pairs {t, x = +-5} and Nf = 20000 interior collocation
points (Latin Hypercube), represents h(t, x) = [u, v] with a 5-layer, 100-neuron
tanh network, and minimizes MSE = MSE0 + MSE_b + MSE_f with

    f = i h_t + 0.5 h_xx + |h|^2 h

evaluated by automatic differentiation.  Reported relative L2 error: 1.97e-3.

Unit mapping (engine <-> paper)
-------------------------------
A(z, T) = A0 * h(t, x) with T = T_s x, z = L_s t turns the paper PDE into the
engine's Agrawal-form equation A_z = -i (beta2/2) A_TT + i gamma |A|^2 A with

    beta2 = -T_s^2 / L_s,      gamma = 1 / (L_s A0^2).

Chosen T_s = 1 ps, L_s = 1 m, A0 = 1 W: beta2 = -1 ps^2/m, gamma = 1 W^-1 m^-1,
peak power 2 W, T0 = 1 ps, span pi/2 m.  (Dimensionless physics; the carrier
wavelength only feeds the unused omega0.)

Checks
------
1. Engine data generation is validated BEFORE any PINN work:
   1a. fundamental-soliton sector: A = sech(T/T0) e^{i z/2} reproduced by the
       engine at z = pi/4 (analytic closed form, machine-precision target);
   1b. independent RK4IP integrator (written here, finer step) vs the engine
       on the N = 2 problem (relative L2 on the final field);
   1c. breather recurrence at z = pi/2: |h| returns to 2 sech(x);
   1d. energy conservation of the engine run.
2. PINN training (torch, float64, fixed seeds): relative L2 against the paper's
   1.97e-3 (accept <= 5e-3), cut profiles at t = 0.59, 0.79, 0.98, MSE0/MSE_b/
   MSE_f history.
3. Stretch: learnable lambda in f = i h_t + 0.5 h_xx + lambda |h|^2 h, init 0.5,
   recovered from the same data (paper's "lambda = 1" inverse direction).

Usage
-----
    python reproductions/planned/raissi_2019_pinn_nlse/reproduce.py
"""

