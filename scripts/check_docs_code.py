#!/usr/bin/env python3
"""Execute the code shown in tutorials and how-to guides, and check its output.

Every ``python`` fence on a page whose front matter says ``quadrant: tutorial``
or ``quadrant: how-to`` is executed, in page order, in one fresh interpreter.
Where a ``text`` fence follows a snippet, the snippet's stdout is compared with
that fence.

    python scripts/check_docs_code.py            # check every page
    python scripts/check_docs_code.py -v         # list each page as it runs

Reference and explanation pages are not executed: they contain signatures and
fragments, not programs.

Warnings and exceptions are treated differently on purpose. stderr is ignored, so
a library warning on one platform cannot fail the gate. An exception fails it.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
EXECUTED = {"tutorial", "how-to"}
# An unlabelled fence is how a page usually writes the output of the snippet above it.
OUTPUT_LANGS = {"", "text", "output"}
FENCE = re.compile(r"```(\w*)\n(.*?)```", re.S)
QUADRANT = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.S)
SENTINEL = "<<<block {}>>>"


def quadrant_of(text: str) -> str:
    m = QUADRANT.match(text)
    if not m:
        return ""
    q = re.search(r"^quadrant:\s*(\S+)", m.group(1), re.M)
    return q.group(1) if q else ""


def parse(text: str) -> list[tuple[str, str]]:
    """Fenced blocks in document order, as (language, body)."""
    return [(lang, body) for lang, body in FENCE.findall(text)]


def norm(text: str) -> list[str]:
    """Lines with trailing whitespace removed and blank lines trimmed at the ends."""
    lines = [ln.rstrip() for ln in text.strip().splitlines()]
    return lines


def run_page(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    blocks = parse(text)

    # Pair each python block with the text block that immediately follows it.
    pairs: list[tuple[str, str | None]] = []
    for i, (lang, body) in enumerate(blocks):
        if lang != "python":
            continue
        nxt = blocks[i + 1] if i + 1 < len(blocks) else None
        expected = nxt[1] if nxt and nxt[0] in OUTPUT_LANGS else None
        pairs.append((body, expected))

    if not pairs:
        return []

    program = [f"# {path.name}: generated by scripts/check_docs_code.py"]
    for i, (body, _) in enumerate(pairs):
        program.append(f"\n# ---- block {i} ----")
        program.append(body)
        program.append(f'print("{SENTINEL.format(i)}")')
    source = "\n".join(program)

    env = {k: v for k, v in os.environ.items() if k != "PYTHONPATH"}
    env["MPLBACKEND"] = "Agg"
    env["PYTHONWARNINGS"] = "ignore"
    with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as fh:
        fh.write(source)
        tmp = fh.name
    try:
        proc = subprocess.run(
            [sys.executable, tmp],
            cwd=ROOT,
            env=env,
            capture_output=True,
            text=True,
            timeout=300,
        )
    finally:
        Path(tmp).unlink(missing_ok=True)

    if proc.returncode != 0:
        tail = "\n".join(proc.stderr.strip().splitlines()[-6:])
        return [f"{path.relative_to(ROOT)}: raised\n    {tail.replace(chr(10), chr(10) + '    ')}"]

    # Each sentinel is printed after its block, so the text preceding a sentinel
    # is that block's output.
    segments = re.split(r"<<<block (\d+)>>>", proc.stdout)
    actual = {int(segments[i]): segments[i - 1] for i in range(1, len(segments) - 1, 2)}

    errors = []
    for i, (_, expected) in enumerate(pairs):
        if expected is None:
            continue
        got, want = norm(actual.get(i, "")), norm(expected)
        if got != want:
            errors.append(
                f"{path.relative_to(ROOT)}: snippet {i} output differs\n"
                f"    recorded: {want}\n"
                f"    actual:   {got}"
            )
    return errors


def main() -> int:
    verbose = "-v" in sys.argv
    pages = sorted(DOCS.rglob("*.md"))
    checked = skipped = 0
    errors: list[str] = []

    for path in pages:
        if quadrant_of(path.read_text(encoding="utf-8")) not in EXECUTED:
            skipped += 1
            continue
        checked += 1
        page_errors = run_page(path)
        status = "FAIL" if page_errors else "ok"
        if verbose or page_errors:
            print(f"{status}: {path.relative_to(ROOT)}")
        errors.extend(page_errors)

    for e in errors:
        print(f"FAIL: {e}")

    if errors:
        print(f"\n{len(errors)} error(s) across {checked} executed page(s)")
        return 1
    print(f"\nOK: {checked} page(s) executed, {skipped} skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
